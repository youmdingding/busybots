/** A name as sign text: upper case, accents dropped, letters the fonts lack become spaces. */
export function signText(name) {
  return String(name || "")
    .normalize("NFD").replace(/[̀-ͯ]/g, "")
    .toUpperCase()
    .split("").map((c) => (c in FONT7 ? c : " ")).join("")
    .replace(/\s+/g, " ").trim();
}

/** Is glyph cell (col, row) lit for `text` laid out from col 0 / row 0 in `font`? */
export function glyphOn(text, col, row, font = FONT7) {
  const gw = font === FONT7 ? 5 : 3, gh = font === FONT7 ? 7 : 5;
  if (row < 0 || row >= gh || col < 0) return false;
  const ci = Math.floor(col / (gw + 1)), cx = col % (gw + 1);
  if (ci >= text.length || cx === gw) return false;
  const g = font[text[ci]] || font[" "];
  return g[row][cx] === "1";
}

/** Width in columns of `text` in `font` (the gap after the last letter left out). */
export const textCols = (text, font = FONT7) => (text.length ? text.length * (font === FONT7 ? 6 : 4) - 1 : 0);
